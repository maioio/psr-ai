"""Documentation engine: reads data.json and writes GitHub-flavored Markdown reports."""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from psr_ai.core.parser import RecordingSession, save_images


# ---------------------------------------------------------------------------
# AI context block - kept deliberately terse so it fits in any LLM prompt
# without burning tokens on whitespace or boilerplate.
# ---------------------------------------------------------------------------

_AI_CONTEXT_HEADER = """\
<!-- AI CONTEXT BLOCK
     Paste this block into any LLM to give it full context of the recorded session.
     Format: STEP | TIMESTAMP | PROGRAM | ACTION
-->
"""

_AI_CONTEXT_FENCE_OPEN = "```text\n"
_AI_CONTEXT_FENCE_CLOSE = "```\n"


# ---------------------------------------------------------------------------
# Markdown report template
# ---------------------------------------------------------------------------

_REPORT_HEADER = """\
# {title}

> Generated by PSR.ai on {date}
> Source: `{source_name}` | Steps: {step_count}

---

"""

_AI_BLOCK = """\
## AI Context Block

{header}\
{fence_open}\
{summary_lines}\
{fence_close}
---

"""

_TOC_HEADER = """\
## Table of Contents

{toc_entries}

---

"""

_TIMELINE_HEADER = "## Step-by-Step Timeline\n\n"

_STEP_BLOCK = """\
### Step {index}: {label}

| Field | Value |
|---|---|
| Timestamp | {timestamp} |
| Program | {program} |
| Action | {action_text} |

{screenshot_line}
---

"""

_SCREENSHOT_LINE = "![Step {index} screenshot]({img_rel})\n"
_NO_SCREENSHOT_LINE = "_No screenshot captured for this step._\n"

_REPORT_FOOTER = """\
---

*Report generated by [PSR.ai](https://github.com/maioio/psr-ai). \
Total steps: {step_count}.*
"""


class MarkdownGenerator:
    """Reads a data.json produced by generate_json_meta and writes report.md.

    The report has three sections in this order:
      1. AI Context Block: a dense one-line-per-step summary for LLM consumption.
      2. Table of Contents: anchor links to every step.
      3. Chronological timeline: each step with metadata table and screenshot.

    Usage:
        gen = MarkdownGenerator(data_json_path)
        report_path = gen.write(output_dir)
    """

    def __init__(self, data_json_path: Path) -> None:
        self._data_path = Path(data_json_path)
        self._data: dict = self._load()

    def _load(self) -> dict:
        return json.loads(self._data_path.read_text(encoding="utf-8"))

    # ------------------------------------------------------------------
    # Public interface
    # ------------------------------------------------------------------

    def write(self, output_dir: Path) -> Path:
        """Render report.md into output_dir and return its path."""
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        content = self._render()
        report_path = output_dir / "report.md"
        report_path.write_text(content, encoding="utf-8")
        return report_path

    # ------------------------------------------------------------------
    # Internal rendering
    # ------------------------------------------------------------------

    def _render(self) -> str:
        d = self._data
        steps = d.get("steps", [])
        title = d.get("title") or "PSR Recording"
        source_name = d.get("source") or "unknown.zip"
        step_count = d.get("step_count", len(steps))
        date = datetime.now().strftime("%Y-%m-%d %H:%M")

        header = _REPORT_HEADER.format(
            title=title,
            date=date,
            source_name=source_name,
            step_count=step_count,
        )

        ai_block = self._render_ai_block(steps, title, source_name)
        toc = self._render_toc(steps)
        timeline = self._render_timeline(steps)
        footer = _REPORT_FOOTER.format(step_count=step_count)

        return header + ai_block + toc + timeline + footer

    def _render_ai_block(self, steps: list[dict], title: str, source: str) -> str:
        """Build the dense AI context block.

        Each line uses the format:
          STEP N | TIMESTAMP | PROGRAM | ACTION
        This lets an LLM read the full session history in minimum tokens.
        """
        if not steps:
            summary_lines = f"No steps recorded. Source: {source}\n"
        else:
            lines = [f"Session: {title} | Source: {source} | Steps: {len(steps)}"]
            for s in steps:
                ts = s.get("timestamp") or "?"
                prog = s.get("program") or "?"
                action = s.get("action_text") or s.get("label") or "?"
                raw_ss = s.get("screenshot", "")
                screenshot = "yes" if raw_ss and _safe_relative(raw_ss) else "no"
                lines.append(
                    f"STEP {s['index']:03d} | {ts} | {prog} | {action} | screenshot:{screenshot}"
                )
            summary_lines = "\n".join(lines) + "\n"

        return _AI_BLOCK.format(
            header=_AI_CONTEXT_HEADER,
            fence_open=_AI_CONTEXT_FENCE_OPEN,
            summary_lines=summary_lines,
            fence_close=_AI_CONTEXT_FENCE_CLOSE,
        )

    def _render_toc(self, steps: list[dict]) -> str:
        if not steps:
            return ""
        entries = []
        for s in steps:
            label = s.get("label") or f"Step {s['index']}"
            anchor = _to_anchor(f"step-{s['index']}-{label}")
            entries.append(f"- [Step {s['index']}: {label}](#{anchor})")
        return _TOC_HEADER.format(toc_entries="\n".join(entries))

    def _render_timeline(self, steps: list[dict]) -> str:
        if not steps:
            return "_No steps were recorded in this session._\n"

        parts = [_TIMELINE_HEADER]
        for s in steps:
            index = s.get("index", 0)
            label = s.get("label") or f"Step {index}"
            timestamp = s.get("timestamp") or "not recorded"
            program = s.get("program") or "not recorded"
            action_text = s.get("action_text") or label

            screenshot_rel = s.get("screenshot", "")
            # _safe_relative returns "" when the path traverses outside the output
            # directory. Treat that the same as a missing screenshot.
            safe_rel = _safe_relative(screenshot_rel) if screenshot_rel else ""
            if safe_rel:
                screenshot_line = _SCREENSHOT_LINE.format(
                    index=index, img_rel=safe_rel
                )
            else:
                screenshot_line = _NO_SCREENSHOT_LINE

            parts.append(_STEP_BLOCK.format(
                index=index,
                label=label,
                timestamp=timestamp,
                program=program,
                action_text=action_text,
                screenshot_line=screenshot_line,
            ))

        return "".join(parts)


