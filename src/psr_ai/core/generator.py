"""Generates Markdown documentation and optional GIF from a RecordingSession."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from psr_ai.core.parser import RecordingSession, save_images


_MD_TEMPLATE = """\
# {title}

> Generated by PSR.ai on {date}

## Summary

| Field | Value |
|---|---|
| Steps recorded | {step_count} |
| Source file | `{source_name}` |
| Generated | {date} |

---

## Step Timeline

{timeline}

---

## AI Agent Context

The following section is structured for direct consumption by AI agents.
Each entry maps to a screenshot saved in `images/`.

```json
{ai_context}
```
"""

_STEP_TEMPLATE = """\
### Step {index}: {label}

![Step {index}]({img_rel})
"""


def generate_markdown(session: RecordingSession, out_dir: Path) -> Path:
    """Write a Markdown file for the session and return its path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    img_dir = out_dir / "images"
    img_paths = save_images(session, img_dir)

    timeline_parts: list[str] = []
    ai_entries: list[str] = []

    for step, img_path in zip(session.steps, img_paths):
        rel = img_path.relative_to(out_dir).as_posix()
        timeline_parts.append(_STEP_TEMPLATE.format(
            index=step.index,
            label=step.label or f"Step {step.index}",
            img_rel=rel,
        ))
        ai_entries.append(
            f'  {{"step": {step.index}, "label": "{step.label}", "image": "{rel}"}}'
        )

    ai_context = "[\n" + ",\n".join(ai_entries) + "\n]"
    content = _MD_TEMPLATE.format(
        title=session.title or "PSR Recording",
        date=datetime.now().strftime("%Y-%m-%d %H:%M"),
        step_count=len(session.steps),
        source_name=session.source_zip.name,
        timeline="\n".join(timeline_parts),
        ai_context=ai_context,
    )

    md_path = out_dir / "session.md"
    md_path.write_text(content, encoding="utf-8")
    return md_path


def generate_gif(session: RecordingSession, out_dir: Path, max_width: int = 1280) -> Path:
    """Assemble an animated GIF from session screenshots.

    Requires Pillow (pip install psr-ai[gif]).
    Frames are resized to max_width before encoding to avoid memory explosion (Pitfall 2).
    """
    try:
        from PIL import Image
    except ImportError as exc:
        raise ImportError(
            "Pillow is required for GIF generation. "
            "Install it with: pip install psr-ai[gif]"
        ) from exc

    img_dir = out_dir / "images"
    if not img_dir.exists():
        save_images(session, img_dir)

    frames: list[Image.Image] = []
    for step in session.steps:
        img_path = img_dir / f"step_{step.index:03d}.png"
        if not img_path.exists():
            continue
        frame = Image.open(img_path).convert("RGB")
        # Resize proportionally to avoid the Pillow GIF memory spike at full resolution.
        if frame.width > max_width:
            ratio = max_width / frame.width
            new_size = (max_width, int(frame.height * ratio))
            frame = frame.resize(new_size, Image.LANCZOS)
        # Quantize to 128 colors: reduces GIF size 30-50% with minimal quality loss.
        frames.append(frame.quantize(colors=128))

    if not frames:
        raise ValueError("No frames found to build GIF.")

    gif_path = out_dir / "session.gif"
    frames[0].save(
        gif_path,
        save_all=True,
        append_images=frames[1:],
        duration=1500,
        loop=0,
        optimize=True,
    )
    return gif_path
