def generate_markdown(session: RecordingSession, out_dir: Path) -> Path:
    """Generate report.md from a RecordingSession.

    Saves images to out_dir/screenshots/, writes data.json, then
    delegates to MarkdownGenerator for the final report.
    Returns the path to report.md.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # Write screenshots so the report can reference them.
    screenshots_dir = out_dir / "screenshots"
    save_images(session, screenshots_dir)

    # Write data.json - the single source of truth the generator reads from.
    from psr_ai.core.parser import generate_json_meta
    data_path = generate_json_meta(session, out_dir / "data.json")

    gen = MarkdownGenerator(data_path)
    return gen.write(out_dir)


def generate_gif(session: RecordingSession, out_dir: Path, max_width: int = 1280) -> Path:
    """Assemble an animated GIF from session screenshots.

    Requires Pillow (pip install psr-ai[gif]).
    Frames are resized to max_width to avoid the Pillow memory spike (Pitfall 2).
    """
    try:
        from PIL import Image
    except ImportError as exc:
        raise ImportError(
            "Pillow is required for GIF generation. "
            "Install it with: pip install psr-ai[gif]"
        ) from exc

    screenshots_dir = Path(out_dir) / "screenshots"
    if not screenshots_dir.exists():
        save_images(session, screenshots_dir)

    frames: list[Image.Image] = []
    for step in session.steps:
        img_path = screenshots_dir / f"step_{step.index:03d}.png"
        if not img_path.exists():
            continue
        frame = Image.open(img_path).convert("RGB")
        # Resize proportionally to cap memory use.
        if frame.width > max_width:
            ratio = max_width / frame.width
            new_size = (max_width, int(frame.height * ratio))
            frame = frame.resize(new_size, Image.LANCZOS)
        # 128 colors reduces GIF size 30-50% with minimal visual loss.
        frames.append(frame.quantize(colors=128))

    if not frames:
        raise ValueError("No frames found to build GIF.")

    gif_path = Path(out_dir) / "session.gif"
    frames[0].save(
        gif_path,
        save_all=True,
        append_images=frames[1:],
        duration=1500,
        loop=0,
        optimize=True,
    )
    return gif_path


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _to_anchor(text: str) -> str:
    """Convert a heading string to a GitHub Markdown anchor slug.

    GitHub lowercases all chars, replaces spaces with hyphens, and strips
    characters that are not alphanumeric, hyphens, or underscores.
    """
    import re
    slug = text.lower()
    slug = re.sub(r"[^\w\s-]", "", slug)
    slug = re.sub(r"[\s_]+", "-", slug)
    slug = slug.strip("-")
    return slug


def _safe_relative(rel: str) -> str:
    """Return a forward-slash path that cannot escape the output directory.

    Strips leading slashes and collapses any '..' components so a crafted
    path in data.json cannot cause the Markdown to reference files outside
    the output directory.
    """
    import posixpath
    # Normalise to forward slashes first.
    normalised = rel.replace("\\", "/")
    # posixpath.normpath collapses '..' but keeps the path relative.
    clean = posixpath.normpath(normalised)
    # Strip any leading '/' or '..' that survived normalisation.
    clean = clean.lstrip("/")
    if clean.startswith(".."):
        return ""
    return clean
